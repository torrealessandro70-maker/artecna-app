/* eslint-disable @typescript-eslint/no-require-imports -- Diagnostica psql solo loopback. */
module.exports=async function({q,admin,titolare,cantiere,fattura,assert}) {
 const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process')
 const sql=fs.readFileSync(path.resolve('supabase/diagnostics/addebiti_origini_readonly.sql'),'utf8')
 const runtime=path.resolve('.run/addebiti-cliente');fs.mkdirSync(runtime,{recursive:true})
 const file=path.join(runtime,'origini-fixture.sql')
 fs.writeFileSync(file,`\\set cantiere_id '${cantiere}'\n\\set fattura_id '${fattura}'\n\\set utente_id '${titolare}'\n`+sql)
 const client=path.resolve('.run/cantiere-prereq-runtime/minimal/pgsql/bin/psql.exe')
 const invoke=file=>cp.spawnSync(client,['-X','-w','--dbname',`host=127.0.0.1 port=${admin.connectionParameters.port} dbname=postgres user=postgres`,'-v','ON_ERROR_STOP=1','-f',file],{encoding:'utf8',windowsHide:true})
 const limited=invoke(file);assert.equal(limited.status,0,limited.stdout+limited.stderr)
 assert.match(limited.stdout,/permessi_applicativi_non_certificati/)
 // Soltanto il DB sintetico riceve questa membership per provare il ramo API.
 await admin.query('GRANT authenticated TO postgres WITH INHERIT FALSE, SET TRUE')
 const result=invoke(file)
 assert.equal(result.status,0,result.stdout+result.stderr)
 assert.equal((result.stdout.match(/^COMMIT\r?$/gm)||[]).length,0)
 assert.equal((result.stdout.match(/^ROLLBACK\r?$/gm)||[]).length,1)
 assert.match(result.stdout,/ARTECNA_ADDEBITI_ORIGINI_READONLY_COMPLETATA/)
 assert.match(result.stdout,/"rpc_assegnazioni_completata": true/)
 assert.match(result.stdout,/mista_cantiere_economia/);assert.match(result.stdout,/riferimento_cantiere_senza_quota_uuid/)
 assert.doesNotMatch(result.stdout,/[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}/i)
 assert.doesNotMatch(result.stdout,/62[.,]00|PERNICONE|Materiale fixture/)
 const blocked=path.join(runtime,'origini-write-fixture.sql')
 fs.writeFileSync(blocked,`\\set cantiere_id '${cantiere}'\n\\set fattura_id '${fattura}'\n\\set utente_id '${titolare}'\n`+sql.replace('RESET ROLE;','RESET ROLE;\nUPDATE public.cantieri SET nome=nome;'))
 const fail=invoke(blocked)
 assert.equal(fail.status,3);assert.match(fail.stderr,/25006/);assert.doesNotMatch(fail.stdout,/ARTECNA_ADDEBITI_ORIGINI_READONLY_COMPLETATA/)
 assert.equal((await q("SELECT current_setting('default_transaction_read_only') v"))[0].v,'off')
 await admin.query('REVOKE authenticated FROM postgres GRANTED BY fixture_admin')
 console.log('DIAGNOSTICA_ORIGINI_GREEN READ_ONLY COMMIT0 ROLLBACK1 output_pseudonimizzato scritture_rifiutate')
}
